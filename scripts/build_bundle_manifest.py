#!/usr/bin/env python
"""Index the unlabeled Sentinel-2 bundle corpus into the manifest FiNo trains from.

The released corpus ships with its manifests; this script rebuilds them.

Usage:
    python scripts/build_bundle_manifest.py --extract <downloads>/*.tar   # extract, then index
    python scripts/build_bundle_manifest.py --root .../S2_unlabeled --jobs 12
    python scripts/build_bundle_manifest.py --root ... --allow-subset      # fewer than 65 bundles

Writes manifest.csv, manifest_rejected.csv, manifest_stats.json and config_fragment.yaml
into the corpus root.
"""

import argparse
import csv
import json
import os
import tarfile
import warnings
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import rasterio
from rasterio.warp import transform as warp_transform

from aquafm.adaptation import bundle_corpus as bc

# rasterio emits a numpy DeprecationWarning per read.
warnings.filterwarnings("ignore", message="Setting the shape on a NumPy array")

EXPECTED_BUNDLES = 65  # one per MGRS tile
# Thresholds, overridable as --max-zero-frac etc.; defaults and meaning in bundle_corpus.
FILTERS = ("max_zero_frac", "max_band_zero_frac", "max_saturated_frac", "min_band_std",
           "min_weakest_band_std", "dead_band_scene_mean")


def extract(archives: list[Path], root: Path, overwrite: bool) -> None:
    """Unpack `<TILE>.tar` bundles into `root`, skipping tiles already present."""
    for archive in archives:
        with tarfile.open(archive) as tar:
            tile = tar.getnames()[0].split("/")[0]
            if (root / tile).exists() and not overwrite:
                print(f"  {tile}: already extracted, skipping")
                continue
            print(f"  {tile}: extracting {archive.name}", flush=True)
            tar.extractall(root, filter="data")


def measure(path: Path, root: Path) -> dict:
    """Name fields, patch-centre lon/lat and quality statistics of one patch."""
    tile, date, index = bc.parse_patch_name(path.stem)
    with rasterio.open(path) as src:
        array = src.read()
        crs, affine = src.crs, src.transform
    if (shape := (bc.NUM_CHANNELS, bc.PATCH_SIZE, bc.PATCH_SIZE)) != array.shape:
        raise SystemExit(f"{path}: shape {array.shape}, expected {shape}; re-extract its bundle.")

    # Per file: the corpus spans several UTM zones.
    x, y = affine * (bc.PATCH_SIZE / 2, bc.PATCH_SIZE / 2)
    (lon,), (lat,) = warp_transform(crs, "EPSG:4326", [x], [y])

    flat = array.reshape(len(array), -1).astype(np.float64)
    return {
        "path": str(path.relative_to(root)),
        "tile": tile,
        "date": date,
        "location_index": index,
        "lon": float(lon),
        "lat": float(lat),
        "crs": str(crs),
        "zero_frac": float((array == 0).all(axis=0).mean()),
        "band_zero_frac": float((array == 0).mean(axis=(1, 2)).max()),
        "saturated_frac": float((array == bc.SATURATION_VALUE).all(axis=0).mean()),
        "band_std": float(array.std()),
        "weakest_band_std": float(flat.std(axis=1).min()),
        "band_means": flat.mean(axis=1),
        "band_sum": flat.sum(axis=1),
        "band_sq_sum": (flat**2).sum(axis=1),
        "pixels": flat.shape[1],
    }


def reject_reasons(r: dict, f: dict) -> str:
    """`+`-joined names of the filters a patch fails, or "" if it is kept."""
    reasons = []
    if r["zero_frac"] > f["max_zero_frac"]:
        reasons.append(f"zero_frac>{f['max_zero_frac']}")
    if r["band_zero_frac"] > f["max_band_zero_frac"]:
        reasons.append(f"band_zero_frac>{f['max_band_zero_frac']}")
    if r["saturated_frac"] > f["max_saturated_frac"]:
        reasons.append(f"saturated_frac>{f['max_saturated_frac']}")
    if r["band_std"] < f["min_band_std"]:
        reasons.append(f"band_std<{f['min_band_std']}")
    if (r["weakest_band_std"] < f["min_weakest_band_std"]
            and max(r["band_means"]) > f["dead_band_scene_mean"]):
        reasons.append(f"weakest_band_std<{f['min_weakest_band_std']}")
    return "+".join(reasons)


FRAGMENT = """\
# Generated by scripts/build_bundle_manifest.py at {created_utc}
# from {root}
{warning}# -> fino_patches/subaqua_vitb16_guided_b768_ref.yaml
crops:
  rgb_mean: [{rgb_mean}]
  rgb_std: [{rgb_std}]
guide:
  guides:
    - name: tile
      method: prototypical
      n_outputs: {tile}
      loss_weight: 0.03
      grl: false
    - name: year
      method: prototypical
      n_outputs: {year}
      loss_weight: 0.03
      grl: true
      grl_space: embedding
# season is available too (n_outputs: {season}) but is not wired by default
"""


def config_fragment(stats: dict) -> str:
    """The training-config values that come from the corpus, as a copy-pasteable block."""
    warning = "" if stats["complete"] else (
        f"# Placeholder values: derived from {stats['bundles_found']}/"
        f"{stats['expected_bundles']} bundles, {stats['patches_kept']} patches.\n"
        "# Re-run build_bundle_manifest.py on the full corpus and re-copy this block.\n"
    )
    return FRAGMENT.format(
        created_utc=stats["created_utc"], root=stats["root"], warning=warning,
        rgb_mean=", ".join(f"{v:.4f}" for v in stats["rgb_mean"]),
        rgb_std=", ".join(f"{v:.4f}" for v in stats["rgb_std"]),
        **stats["guide_cardinalities"],
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    data_root = Path(os.environ.get("AQUAFM_DATA_ROOT", "data"))
    parser.add_argument("--root", type=Path, default=data_root / "S2_unlabeled")
    parser.add_argument("--extract", type=Path, nargs="+", default=[], metavar="TAR")
    parser.add_argument("--overwrite", action="store_true", help="re-extract existing tiles")
    parser.add_argument("--expected-bundles", type=int, default=EXPECTED_BUNDLES)
    parser.add_argument("--allow-subset", action="store_true", help="skip the bundle-count check")
    parser.add_argument("--jobs", type=int, default=4, help="raster-reading threads")
    for name in FILTERS:
        parser.add_argument(f"--{name.replace('_', '-')}", type=float,
                            default=getattr(bc, name.upper()))
    args = parser.parse_args()
    filters = {name: getattr(args, name) for name in FILTERS}

    args.root.mkdir(parents=True, exist_ok=True)
    extract(args.extract, args.root, args.overwrite)
    tiles = sorted(d.name for d in args.root.iterdir() if d.is_dir())
    if not args.allow_subset and len(tiles) != args.expected_bundles:
        raise SystemExit(f"Found {len(tiles)} bundles in {args.root}, expected "
                         f"{args.expected_bundles}; pass --allow-subset to index a subset.")
    paths = [p for tile in tiles for p in sorted((args.root / tile).glob("*.tif"))]
    print(f"Scanning {len(paths)} patches in {len(tiles)} bundles")
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        records = list(pool.map(lambda p: measure(p, args.root), paths))

    kept, rejected = [], []
    for record in records:
        if reason := reject_reasons(record, filters):
            rejected.append({**record, "reason": reason})
        else:
            kept.append(record)
    if not kept:
        raise SystemExit(f"All {len(records)} patches were rejected; check the filter thresholds.")

    for record in kept:
        record["year"] = int(record["date"][:4])
        record["month"] = int(record["date"][4:6])
        record["season"] = bc.season_of(record["month"], record["lat"])
    # Sorted, so each guide label's integer is reproducible from the stats file alone.
    vocabularies = {field: sorted({r[field] for r in kept})
                    for field in ("tile", "year", "season", "month", "date")}

    pixels = sum(r["pixels"] for r in kept)
    means = np.sum([r["band_sum"] for r in kept], axis=0) / pixels
    sq_means = np.sum([r["band_sq_sum"] for r in kept], axis=0) / pixels
    stds = np.sqrt(np.clip(sq_means - means**2, 1e-12, None))

    stats = {
        "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "root": args.root.resolve().name,
        "complete": len(tiles) == args.expected_bundles,
        "expected_bundles": args.expected_bundles,
        "bundles_found": len(tiles),
        "patches_scanned": len(records),
        "patches_kept": len(kept),
        "patches_rejected": len(rejected),
        "rejected_by_reason": dict(sorted(Counter(r["reason"] for r in rejected).items())),
        "filters": filters,
        "vocabularies": vocabularies,
        "guide_cardinalities": {field: len(vocabularies[field]) for field in bc.GUIDE_FIELDS},
        "channel_names": list(bc.CHANNEL_NAMES),
        # 0..1 units: FiNo normalizes after ToDtype(float32, scale=True).
        "rgb_mean": (means / 255.0).tolist(),
        "rgb_std": (stds / 255.0).tolist(),
        "rgb_mean_dn": means.tolist(),
        "rgb_std_dn": stds.tolist(),
        "per_tile": {
            tile: {
                "patches": sum(1 for r in kept if r["tile"] == tile),
                "rejected": sum(1 for r in rejected if r["tile"] == tile),
                "dates": sorted({r["date"] for r in kept if r["tile"] == tile}),
                "locations": len({r["location_index"] for r in kept if r["tile"] == tile}),
                "crs": sorted({r["crs"] for r in kept if r["tile"] == tile}),
            }
            for tile in vocabularies["tile"]
        },
    }

    with (args.root / bc.MANIFEST_NAME).open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=bc.MANIFEST_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        for r in sorted(kept, key=lambda r: r["path"]):
            writer.writerow({
                **r,
                **{k: f"{r[k]:.6f}" for k in ("lon", "lat", "zero_frac", "band_zero_frac",
                                              "saturated_frac")},
                **{k: f"{r[k]:.3f}" for k in ("band_std", "weakest_band_std")},
                **{f"mean_{c}": f"{m:.3f}" for c, m in zip(bc.CHANNEL_NAMES, r["band_means"])},
            })
    with (args.root / bc.REJECTED_NAME).open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=bc.REJECTED_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(sorted(rejected, key=lambda r: r["path"]))
    (args.root / bc.STATS_NAME).write_text(json.dumps(stats, indent=2))
    (args.root / bc.FRAGMENT_NAME).write_text(config_fragment(stats))

    print(f"Kept {len(kept)}/{len(records)} patches; rejected {stats['rejected_by_reason']}")
    print(f"Guide cardinalities {stats['guide_cardinalities']}; wrote manifests to {args.root}")


if __name__ == "__main__":
    main()
